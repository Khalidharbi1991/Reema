# Simple markdown to HTML conversion (basic - headers, lists, tables, bold, code)
import re

html_content = content

# Remove YAML frontmatter
html_content = re.sub(r'^---\n.*?\n---\n', '', html_content, flags=re.DOTALL)

# Convert headers
html_content = re.sub(r'^#### (.*?)$', r'<h4>\1</h4>', html_content, flags=re.MULTILINE)
html_content = re.sub(r'^### (.*?)$', r'<h3>\1</h3>', html_content, flags=re.MULTILINE)
html_content = re.sub(r'^## (.*?)$', r'<h2>\1</h2>', html_content, flags=re.MULTILINE)
html_content = re.sub(r'^# (.*?)$', r'<h1>\1</h1>', html_content, flags=re.MULTILINE)

# Convert horizontal rules
html_content = html_content.replace('---', '<hr>')

# Convert bold text
html_content = re.sub(r'\*\*(.*?)\*\*', r'<strong>\1</strong>', html_content)

# Convert inline code
html_content = re.sub(r'`([^`]+)`', r'<code>\1</code>', html_content)

# Convert code blocks
html_content = re.sub(r'```(.*?)```', r'<pre><code>\1</code></pre>', html_content, flags=re.DOTALL)

# Convert bullet lists
lines = html_content.split('\n')
new_lines = []
in_list = False
for line in lines:
    if line.strip().startswith('- ') or line.strip().startswith('* ') or line.strip().startswith('• '):
        if not in_list:
            new_lines.append('<ul>')
            in_list = True
        item = line.strip()[2:].strip()
        new_lines.append(f'<li>{item}</li>')
    else:
        if in_list:
            new_lines.append('</ul>')
            in_list = False
        new_lines.append(line)

html_content = '\n'.join(new_lines)

# Convert line breaks to paragraphs
paragraphs = html_content.split('\n\n')
formatted_paragraphs = []
for p in paragraphs:
    p = p.strip()
    if p and not p.startswith('<') and not p.startswith('|'):
        formatted_paragraphs.append(f'<p>{p}</p>')
    else:
        formatted_paragraphs.append(p)

html_content = '\n\n'.join(formatted_paragraphs)

# Create final HTML
html_output = html_template.format(
    content=html_content,
    date=datetime.now().strftime("%Y-%m-%d %H:%M:%S")
)

# Write HTML file
html_file = Path("teams/documentation/output/html/Workstation_Security_Patches_SOP.html")
with open(html_file, 'w', encoding='utf-8') as f:
    f.write(html_output)

print(f"✅ HTML created: {html_file}")

