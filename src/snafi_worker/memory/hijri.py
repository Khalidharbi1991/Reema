_STARTS = {(y, m): date.fromisoformat(s) for y, m, s in MONTH_STARTS}
_ORDERED = sorted((start, y, m) for (y, m), start in _STARTS.items())


def month_length(year: int, month: int) -> Optional[int]:
    """Days in a Hijri month (29 or 30), or None outside the table."""
    start = _STARTS.get((year, month))
    nxt = _STARTS.get((year, month + 1) if month < 12 else (year + 1, 1))
    if start is None or nxt is None:
        return None
    return (nxt - start).days


def to_gregorian(year: int, month: int, day: int) -> Optional[date]:
    """The Gregorian date of a Hijri date. Day 30 in a 29-day month falls on that month's last day.
    None outside the table."""
    length = month_length(year, month)
    if length is None or not 1 <= day <= 30:
        return None
    return _STARTS[(year, month)] + timedelta(days=min(day, length) - 1)


def to_hijri(day: date) -> Optional[Tuple[int, int, int]]:
    """(year, month, day) in the Hijri calendar, or None outside the table."""
    best = None
    for start, y, m in _ORDERED:
        if start > day:
            break
        best = (start, y, m)
    if best is None or month_length(best[1], best[2]) is None:
        return None
    return best[1], best[2], (day - best[0]).days + 1
